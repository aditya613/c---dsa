#include <bits/stdc++.h>
using namespace std;

class Book {
private:
    int bookID;
    string title;
    bool available;
    int timesIssued;
    double accumulatedFine;

public:
    Book(int id, string name) {
        bookID = id;
        title = name;
        available = true;
        timesIssued = 0;
        accumulatedFine = 0;
    }

    void issueBook() {
        if (!available) {
            cout << title << " is already issued!" << endl;
        } 
        else {
            available = false;
            timesIssued++;
            cout << title << " issued successfully." << endl;
        }
    }

    void returnBook(int lateDays) {
        if (available) {
            cout << title << " was not issued!" << endl;
            return;
        }

        available = true;
        calculateFine(lateDays);

        cout << title << " returned successfully." << endl;
    }

    void calculateFine(int lateDays) {
        const double finePerDay = 10;

        if (lateDays > 0) {
            accumulatedFine += lateDays * finePerDay;

            cout << "Fine: Rs. "
                 << lateDays * finePerDay << endl;
        }
    }

    int getTimesIssued() {
        return timesIssued;
    }

    double getFine() {
        return accumulatedFine;
    }

    string getTitle() {
        return title;
    }

    void display() {
        cout << endl << "Book ID: " << bookID << endl;
        cout << "Title: " << title << endl;
        cout << "Status: "
             << (available ? "Available" : "Issued") << endl;
        cout << "Times Issued: " << timesIssued << endl;
        cout << "Accumulated Fine: Rs. "
             << accumulatedFine << endl;
    }
};

int main() {
    Book b1(101, "C++ Programming");
    Book b2(102, "Data Structures");
    Book b3(103, "Database Management");

    b1.issueBook();
    b1.issueBook();
    b1.returnBook(2);

    b1.issueBook();
    b1.returnBook(0);

    b2.issueBook();
    b2.returnBook(5);

    b3.issueBook();
    b3.returnBook(1);

    Book* books[] = {&b1, &b2, &b3};
    int n = 3;

    int maxIssued = 0;
    int maxFine = 0;

    for (int i = 1; i < n; i++) {
        if (books[i]->getTimesIssued() >
            books[maxIssued]->getTimesIssued()) {
            maxIssued = i;
        }

        if (books[i]->getFine() >
            books[maxFine]->getFine()) {
            maxFine = i;
        }
    }

    cout << endl << endl << "--- LIBRARY BOOK DETAILS ---" << endl;

    for (int i = 0; i < n; i++) {
        books[i]->display();
    }

    cout << endl << "--- FINAL RESULTS ---" << endl;

    cout << "Most Frequently Issued Book: "
         << books[maxIssued]->getTitle() << endl;

    cout << "Maximum Fine Generated By: "
         << books[maxFine]->getTitle()
         << " (Rs. " << books[maxFine]->getFine()
         << ")" << endl;

    return 0;
}