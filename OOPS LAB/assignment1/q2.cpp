#include<bits/stdc++.h>
using namespace std;

int main(){
      char chr = 'a';
    float flt = 201.10;
    double dbt = 150000000;
    bool boolean = true;
    short shrt =2500;
    long lng = 1200000000;
    long long ll = 1400000;

    cout<< "Size of Char Value: "<<sizeof(chr)<<endl;
    cout<<"Size of Float Value: "<<sizeof(flt)<<endl;
    cout<<"Size of Double Value: "<<sizeof(dbt)<<endl;
    cout<<"Size of Boolean Value: "<<sizeof(boolean)<<endl;
    cout<<"Size of Short Value: "<<sizeof(shrt)<<endl;
    cout<<"Size of Long Value: "<<sizeof(lng)<<endl;
    cout<<"Size of Long Long Value: "<<sizeof(ll)<<endl;

    return 0;

}